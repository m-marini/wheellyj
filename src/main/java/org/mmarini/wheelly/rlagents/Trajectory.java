package org.mmarini.wheelly.rlagents;

import org.nd4j.linalg.api.ndarray.INDArray;

import java.util.Map;

import static java.util.Objects.requireNonNull;

/**
 * Represents an unrolled, chronologically aligned sequence of historical experiences
 * generated by a Reinforcement Learning agent.
 * <p>
 * This record serves as an immutable data container designed to encapsulate the complete state
 * transitions, corresponding actions, and scalar rewards required to compute policy gradients,
 * temporal difference errors, or value function approximations. Memory allocations inside the
 * underlying ND4J tensors are mapped to native off-heap storage and are managed via the
 * {@link AutoCloseable} interface lifecycle.
 * </p>
 *
 * @param states  A dictionary mapping string identifiers to their respective observation tensor sequences.
 *                For an execution trajectory of length {@code n}, this structure contains {@code n + 1}
 *                elements to accommodate the final terminal state snapshot.
 * @param actions A dictionary mapping string identifiers to their respective chosen action tensor sequences
 *                comprising {@code n} elements.
 * @param rewards An ND4J array containing the sequence of {@code n} scalar reinforcement learning feedback rewards.
 */
public record Trajectory(Map<String, INDArray> states, Map<String, INDArray> actions,
                         INDArray rewards) implements AutoCloseable {
    /**
     * Compact constructor for state validation.
     * <p>
     * Guarantees that none of the provided experience components are null before
     * binding them to the immutable fields of the trajectory record.
     * </p>
     *
     * @throws NullPointerException if any of the mapped data containers ({@code states},
     *                              {@code actions}, or {@code rewards}) are null.
     */
    public Trajectory {
        requireNonNull(states);
        requireNonNull(actions);
        requireNonNull(rewards);
    }

    @Override
    public void close() {
        rewards.close();
        for (INDArray value : states.values()) {
            value.close();
        }
        for (INDArray value : actions.values()) {
            value.close();
        }
    }

    /**
     * Returns the discrete operational length of the trajectory sequence.
     * <p>
     * The returned count represents the total number of unrolled transition steps, which equates
     * mathematically to {@code (#states - 1) = #actions = #rewards}.
     * </p>
     *
     * @return The number of step intervals comprising this trajectory sequence.
     */
    public long size() {
        return rewards.size(0);
    }
}
